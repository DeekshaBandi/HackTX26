-- 1. Run make_key.py first and copy the key it prints.
-- 2. Paste it below where it says PASTE_KEY_HERE (keep the quotes).
-- 3. Run All.

USE ROLE ACCOUNTADMIN;

-- A role that can only touch our project
CREATE ROLE IF NOT EXISTS AIEDH_APP_ROLE;
GRANT USAGE ON WAREHOUSE AIEDH_WH TO ROLE AIEDH_APP_ROLE;
GRANT USAGE ON DATABASE AIEDH TO ROLE AIEDH_APP_ROLE;
GRANT USAGE ON SCHEMA AIEDH.MATCHING TO ROLE AIEDH_APP_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA AIEDH.MATCHING TO ROLE AIEDH_APP_ROLE;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA AIEDH.MATCHING TO ROLE AIEDH_APP_ROLE;
GRANT CREATE TABLE ON SCHEMA AIEDH.MATCHING TO ROLE AIEDH_APP_ROLE;

-- The app user (TYPE = SERVICE means it's for code, not a person)
CREATE USER IF NOT EXISTS AIEDH_APP
  TYPE = SERVICE
  DEFAULT_ROLE = AIEDH_APP_ROLE
  DEFAULT_WAREHOUSE = AIEDH_WH
  DEFAULT_NAMESPACE = AIEDH.MATCHING;

ALTER USER AIEDH_APP SET RSA_PUBLIC_KEY = 'PASTE_KEY_HERE';

GRANT ROLE AIEDH_APP_ROLE TO USER AIEDH_APP;